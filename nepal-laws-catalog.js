  function tokenize(text) {
    return String(text || '')
      .toLowerCase()
      .replace(/[०-९]/g, (d) => '0123456789'['०१२३४५६७८९'.indexOf(d)])
      .replace(/[^\u0900-\u097Fa-z0-9\s]/g, ' ')
      .split(/\s+/)
      .filter((w) => w.length >= 2 && !STOP.has(w));
  }

  function actTokens(actName) {
    return tokenize(actName).filter((w) => w.length >= 3 && !/^\d+$/.test(w));
  }

  function defaultDescription(actName) {
    return 'उजुरीमा उल्लेखित विषयसँग सम्बन्धित प्रचलित कानुनी व्यवस्था (' + actName + ')।';
  }

  function suggestLawsFromComplaint(text, limit) {
    limit = limit || 3;
    const hay = String(text || '').toLowerCase();
    const hayTokens = new Set(tokenize(hay));
    const scores = new Map();

    function addScore(actName, pts) {
      if (!actName || !NEPAL_ACT_NAMES.includes(actName)) return;
      scores.set(actName, (scores.get(actName) || 0) + pts);
    }

    LAW_THEMES.forEach((theme) => {
      const hit = theme.keywords.some((k) => hay.includes(k.toLowerCase()));
      if (hit) theme.acts.forEach((a) => addScore(a, 4));
    });

    NEPAL_ACT_NAMES.forEach((actName) => {
      const tokens = actTokens(actName);
      let s = 0;
      tokens.forEach((t) => {
        if (hay.includes(t)) s += 2;
        if (hayTokens.has(t)) s += 1;
      });
      if (s > 0) addScore(actName, s);
    });

    return Array.from(scores.entries())
      .sort((a, b) => b[1] - a[1])
      .slice(0, limit)
      .map(([name, score]) => ({ name, score, description: defaultDescription(name) }));
  }

